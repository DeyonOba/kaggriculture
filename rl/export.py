"""Export trained weights into kagent/weights.py and build the RL bundle.

Usage:
    PYTHONPATH=. uv run python rl/export.py rl/runs/r1/best_weights.json --freeze rl-v1
"""

import argparse
import json
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("weights_json", nargs="?", default=None, help="best_weights.json from a training run")
    ap.add_argument("--freeze", default=None)
    ap.add_argument("--clear", action="store_true", help="reset weights.py to None (heuristic)")
    ap.add_argument("--mpc", action="store_true", help="enable the MPC day-planner in the bundle")
    ap.add_argument("--champion", action="store_true", help="run the champion playbook plan as the primary policy")
    ap.add_argument("--residual", action="store_true", help="weights are offset heads over the champion plan")
    ap.add_argument("--exec", dest="exec_rules", default=None,
                    help="comma-separated kagent/scheduler.EXEC_FLAGS to enable in the bundle")
    ap.add_argument("--bandit-rules", default=None, help="rl/bandit.py rules.json to embed (BanditPolicy over the champion plan)")
    ap.add_argument("--theta", default=None,
                    help="a searched strategy vector (tools/cem_theta.py's "
                         "best_theta.json) to embed. Its own exec list becomes "
                         "EXEC_RULES unless --exec overrides it.")
    args = ap.parse_args()
    if not args.clear and not args.weights_json:
        ap.error("weights_json required unless --clear")
    theta_literal = "None"
    theta_exec = None
    if args.theta:
        with open(args.theta) as f:
            t = json.load(f)
        knobs = t.get("knobs", t)
        from kagent import planner as _pl
        unknown = [k for k in knobs if k not in _pl.KNOB_DEFAULTS]
        if unknown:
            ap.error(f"theta carries knobs the planner does not read: {unknown}")
        theta_literal = repr(knobs)
        theta_exec = list(t.get("exec") or [])
        if args.bandit_rules:
            ap.error("--theta and --bandit-rules are alternatives, not layers: "
                     "the vector fixes every knob from day 0 and the bandit "
                     "decides four of them at day 6+, so a bundle carrying both "
                     "could not be attributed")

    exec_literal = "None"
    if args.exec_rules is None and theta_exec is not None:
        exec_literal = repr(theta_exec)
    if args.exec_rules:
        from kagent import scheduler as _sched
        flags = [f.strip() for f in args.exec_rules.split(",") if f.strip()]
        bad = [f for f in flags if f not in _sched.EXEC_FLAGS]
        if bad:
            ap.error(f"unknown executor flag(s) {bad}; known: {_sched.EXEC_FLAGS}")
        exec_literal = repr(flags)
    rules_literal = "None"
    if args.bandit_rules:
        with open(args.bandit_rules) as f:
            rules_literal = repr(json.load(f))

    out = os.path.join(REPO, "kagent", "weights.py")
    if args.clear:
        body = (
            '"""Neural planner weights (generated by rl/export.py; None -> heuristic)."""\n\n'
            "WEIGHTS_DATA = None\nMPC_ENABLED = False\n"
            f"CHAMPION_PLAN = {bool(args.champion)!r}\n"
            f"BANDIT_RULES = {rules_literal}\n"
            f"THETA_KNOBS = {theta_literal}\n"
            f"EXEC_RULES = {exec_literal}\n"
        )
    else:
        with open(args.weights_json) as f:
            data = json.load(f)
        body = (
            '"""Neural planner weights (generated by rl/export.py; None -> heuristic)."""\n\n'
            f"WEIGHTS_DATA = {data!r}\n"
            f"MPC_ENABLED = {bool(args.mpc)!r}\n"
            f"CHAMPION_PLAN = {bool(args.champion)!r}\n"
            f"RESIDUAL = {bool(args.residual)!r}\n"
            f"BANDIT_RULES = {rules_literal}\n"
            f"THETA_KNOBS = {theta_literal}\n"
            f"EXEC_RULES = {exec_literal}\n"
        )
    with open(out, "w") as f:
        f.write(body)
    print(f"wrote {out} ({len(body)} bytes)")

    cmd = [sys.executable, os.path.join(REPO, "tools", "build_submission.py")]
    if args.freeze:
        cmd += ["--freeze", args.freeze]
    subprocess.run(cmd, check=True)


if __name__ == "__main__":
    main()
