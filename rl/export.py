"""Export trained weights into kagent/weights.py and build the RL bundle.

Usage:
    PYTHONPATH=. uv run python rl/export.py rl/runs/r1/best_weights.json --freeze rl-v1
"""

import argparse
import json
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("weights_json", nargs="?", default=None, help="best_weights.json from a training run")
    ap.add_argument("--freeze", default=None)
    ap.add_argument("--clear", action="store_true", help="reset weights.py to None (heuristic)")
    args = ap.parse_args()
    if not args.clear and not args.weights_json:
        ap.error("weights_json required unless --clear")

    out = os.path.join(REPO, "kagent", "weights.py")
    if args.clear:
        body = '"""Neural planner weights (generated by rl/export.py; None -> heuristic)."""\n\nWEIGHTS_DATA = None\n'
    else:
        with open(args.weights_json) as f:
            data = json.load(f)
        body = (
            '"""Neural planner weights (generated by rl/export.py; None -> heuristic)."""\n\n'
            f"WEIGHTS_DATA = {data!r}\n"
        )
    with open(out, "w") as f:
        f.write(body)
    print(f"wrote {out} ({len(body)} bytes)")

    cmd = [sys.executable, os.path.join(REPO, "tools", "build_submission.py")]
    if args.freeze:
        cmd += ["--freeze", args.freeze]
    subprocess.run(cmd, check=True)


if __name__ == "__main__":
    main()
