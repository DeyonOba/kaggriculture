"""Neural day-planner: a tiny masked multi-discrete MLP in pure stdlib.

The network only replaces the STRATEGIC fields of DayPlan (quotas, animal
buys, hires, land, melon floor) once per day; the proven scripted scheduler
and market controller execute the micro. ~25k multiply-adds per day-decision,
so inference cost is irrelevant next to the 1s/step budget.

Weights ship as base85-encoded float32 in kagent/weights.py (generated by
rl/export.py; None by default -> HeuristicPolicy is used instead).
"""

import base64
import math
import struct

from kagent import features, planner


def decode_weights(data):
    """{"sizes": [...], "b85": str} -> list of per-layer [W (rows list), b]."""
    if not data:
        return None
    raw = base64.b85decode(data["b85"].encode("ascii"))
    flat = list(struct.unpack("<%df" % (len(raw) // 4), raw))
    sizes = data["sizes"]  # [(in, out), ...]
    layers = []
    pos = 0
    for n_in, n_out in sizes:
        w = []
        for _ in range(n_in):
            w.append(flat[pos : pos + n_out])
            pos += n_out
        b = flat[pos : pos + n_out]
        pos += n_out
        layers.append((w, b))
    return layers


def _matvec(w, b, x):
    out = list(b)
    for i, xi in enumerate(x):
        if xi == 0.0:
            continue
        row = w[i]
        for j in range(len(out)):
            out[j] += xi * row[j]
    return out


def forward(layers, x):
    """Returns (action_logits, value). Layers: h1, h2, logits, value."""
    h = [math.tanh(v) for v in _matvec(layers[0][0], layers[0][1], x)]
    h = [math.tanh(v) for v in _matvec(layers[1][0], layers[1][1], h)]
    logits = _matvec(layers[2][0], layers[2][1], h)
    value = _matvec(layers[3][0], layers[3][1], h)[0]
    return logits, value


def choose(logits, head_masks, rng=None, temperature=1.0):
    """Split flat logits by head, mask, and pick (argmax, or sample if rng).

    Returns (choices, logprob_sum). Masked-before-softmax keeps the policy
    gradient unbiased (Huang & Ontanon 2020).
    """
    choices = []
    logprob = 0.0
    pos = 0
    t = temperature if (rng is not None and temperature > 0) else 1.0
    for (name, vals), mask in zip(features.HEADS, head_masks):
        n = len(vals)
        seg = logits[pos : pos + n]
        pos += n
        masked = [(seg[i] / t if mask[i] else -1e9) for i in range(n)]
        mx = max(masked)
        exps = [math.exp(v - mx) for v in masked]
        total = sum(exps)
        probs = [e / total for e in exps]
        if rng is None:
            idx = max(range(n), key=lambda i: probs[i])
        else:
            r = rng.random()
            acc = 0.0
            idx = n - 1
            for i, p in enumerate(probs):
                acc += p
                if r <= acc:
                    idx = i
                    break
        choices.append(idx)
        logprob += math.log(max(probs[idx], 1e-12))
    return choices, logprob


class NeuralPolicy:
    """Day-plan provider: heuristic base plan, strategic fields overridden by
    the network. Plugs into HeuristicPolicy via its plan_provider seam.
    Falls back to the pure heuristic plan when no weights are loaded."""

    def __init__(self, layers, temperature=1.0, rng=None):
        self.layers = layers
        self.temperature = temperature
        self.rng = rng
        self.last_decision = None  # (features, masks, choices, logprob, value)

    def make_plan(self, view, memory):
        plan = planner.make_day_plan(view, memory)
        if self.layers is None:
            return plan
        x = features.encode(view, memory)
        head_masks = features.masks(view)
        logits, value = forward(self.layers, x)
        choices, logprob = choose(
            logits, head_masks, rng=self.rng, temperature=self.temperature
        )
        self.last_decision = (x, head_masks, choices, logprob, value)
        return features.apply_to_plan(plan, choices, view)
