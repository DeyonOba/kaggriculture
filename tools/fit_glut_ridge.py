"""Fit and export the melon glut-day ridge, plus the hard-coded verdicts.

`tools/glut_target.py` measured which products are worth predicting at all:

    MELON       R2 0.986  MAE 0.25d  decision-error 0.1% at m=12   -> PREDICT
    FERTILIZER  gluts on day 1 in 100% of windows, sd 0.3          -> CONSTANT
    TOMATO      gluts in  3% of 15-day windows                     -> CONSTANT
    CARROT      gluts in  8%                                       -> CONSTANT
    MILK/WOOL/STRAWBERRY  predictable but 0.37-0.55 unexplained    -> later

A ridge on POOLED CHANNEL MEANS already answers melon essentially perfectly, so
a CNN has nothing to add there. 85 coefficients instead of 327k weights, and
the same verified encoder.

Scored on DECISION ERROR, not RMSE: the consumer is a boolean gate ("will it
glut before my crop matures?"), where a 1-day error at the boundary flips the
decision and a 5-day error far from it changes nothing. RMSE weights the
harmless one 25x more. Reported MAE is on UNCENSORED samples only -- carrot is
92% censored, so its aggregate MAE of 1.80 is mostly scoring the constant 15
while its uncensored error is 9.66.

    PYTHONPATH=. uv run python tools/fit_glut_ridge.py --out /tmp/glut.py
"""

import argparse
import os
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

DATA = os.path.join(REPO, "rl/datasets/glut.npz")
PRODUCTS = ["WHEAT", "CARROT", "TOMATO", "STRAWBERRY", "MELON",
            "EGG", "MILK", "WOOL", "FERTILIZER"]
MELON_MATURES = 12          # CROPS["MELON"]["max_yield_day"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--arm", default="E_full_83")
    ap.add_argument("--lam", type=float, default=1.0)
    args = ap.parse_args()

    from tools.board_tensor import arm_channels
    d = np.load(DATA)
    T, Y, C, D, G = d["T"], d["Y"], d["C"], d["D"], d["G"]
    cols = arm_channels(args.arm)
    X = T[:, cols].mean(axis=(2, 3))
    X = np.hstack([X, D[:, None].astype("float32"),
                   np.ones((len(X), 1), "float32")])
    mi = PRODUCTS.index("MELON")
    y = Y[:, mi]

    # held-out BY GAME, for an honest read of the decision error
    gids = np.unique(G)
    pred = np.zeros_like(y)
    for f in range(5):
        te = np.isin(G, gids[f::5])
        tr = ~te
        A = X[tr].T @ X[tr] + args.lam * np.eye(X.shape[1], dtype="float32")
        pred[te] = X[te] @ np.linalg.solve(A, X[tr].T @ y[tr])
    r2 = 1 - ((y - pred) ** 2).sum() / max(1e-9, ((y - y.mean()) ** 2).sum())
    mae = float(np.abs(y - pred).mean())
    wrong = float(((y < MELON_MATURES) != (pred < MELON_MATURES)).mean())
    # asymmetric: predicting glut LATE means planting into a crash
    late = float(((y < MELON_MATURES) & (pred >= MELON_MATURES)).mean())
    early = float(((y >= MELON_MATURES) & (pred < MELON_MATURES)).mean())
    print(f"  MELON held-out by game: R2 {r2:.3f}  MAE {mae:.2f} days")
    print(f"    decision error at m={MELON_MATURES}: {100*wrong:.2f}%"
          f"   (too LATE {100*late:.2f}% = plant into a crash,"
          f"  too EARLY {100*early:.2f}% = skip a good plant)")

    # refit on everything for export
    A = X.T @ X + args.lam * np.eye(X.shape[1], dtype="float32")
    W = np.linalg.solve(A, X.T @ y).astype("float32")

    src = [
        '"""Melon glut-day ridge and the hard-coded glut verdicts (generated).\n\n'
        'Generated by tools/fit_glut_ridge.py. 85 coefficients over the pooled\n'
        'channel means of the verified encoder, plus the day index and a bias.\n'
        f'Held out by game: R2 {r2:.3f}, decision error {100*wrong:.2f}% at\n'
        f'maturity {MELON_MATURES}.\n"""\n',
        "_GLUT_COLS = %r" % (cols,),
        "_GLUT_W = %r" % (W.tolist(),),
        "_GLUT_MELON_MATURES = %d" % MELON_MATURES,
        "# products that effectively never glut inside a 15-day window",
        "# (carrot 8%, tomato 3%): no constraint, no model.",
        '_GLUT_NEVER = ("CARROT", "TOMATO")',
        "# fertilizer gluts on day 1 in 100% of windows (sd 0.3) but is never",
        "# planted, so it needs no plant-side rule.",
        '''

def _glut_melon_days(obs):
    """Predicted days until MELON inventory crosses I0."""
    t = board_pair_full(obs, obs.get("player", 0))
    v = t[_GLUT_COLS].mean(axis=(1, 2))
    x = _np.concatenate([v, _np.asarray([float(obs.get("day", 0)), 1.0],
                                        dtype=_np.float32)])
    return float(x @ _np.asarray(_GLUT_W, dtype=_np.float32))
''',
    ]
    open(args.out, "w").write("\n".join(src))
    print(f"  -> {args.out} ({os.path.getsize(args.out)} bytes,"
          f" {len(W)} coefficients)")


if __name__ == "__main__":
    main()
