"""V(s) trained on SEARCH OUTCOMES instead of corpus co-occurrence.

The diagnosis this answers, measured in `tau_derive` on 2026-09-20:

    head        blind   sees   sign accuracy
    aggregate    68%     46    0.609 +/- 0.072
    spatial       0%    143    0.455 +/- 0.042   <- +15.4% logloss, still chance

Refitting the ENCODER cured blindness and bought nothing on ordering. Both
heads were fit on recorded games, where the label is "this state occurred in
a game somebody won". That teaches CO-OCCURRENCE, and co-occurrence is a
property of the LABELS, so no encoder touches it. This file changes the
labels.

THE LABEL. Take a real state s, apply action a, then PLAY THE REST OF THE
GAME OUT with a fixed policy on a fixed seed. The label is what actually
happened. Do it again from the same s with a different action b. Now the
difference between the two labels is caused by the action and nothing else
-- a counterfactual, not a correlation.

WHY K BRANCHES PER STATE. K playouts from one state yield K*(K-1)/2 ordered
pairs, and the pair is the unit of signal: sign(V(a) - V(b)) against
sign(outcome(a) - outcome(b)) is exactly the statistic that says chance
today. K=4 gives 6 pairs for 4 playouts.

WHY REPLAY AND NOT FORK. Forking the env is faithful -- deepcopy is isolated
and the engine derives its randomness per day from (seed, day). The AGENT is
not: it carries mid-game state, so a fresh instance handed a forked position
plays differently from one that saw the game from the start (measured:
62,860/75,740 forked against 62,288/69,458 continuous, same seed). Replaying
from step 0 resets it. That costs ~2.5x and is what `tau_derive` does, so
training labels and the evaluation metric are generated by the same process.

    PYTHONPATH=. uv run python tools/value_search.py build --n 1200 --k 4
    PYTHONPATH=. uv run python tools/value_search.py fit
"""
import argparse
import multiprocessing as mp
import os
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
DATA = os.path.join(REPO, "rl/datasets/value_search.npz")
TENS = os.path.join(REPO, "rl/datasets/value_search_T.npy")
MODEL = os.path.join(REPO, "rl/datasets/value_search_model.npz")
# day at which money_lead becomes decisive (propagation: r=0.699)
AUX_DAY = 20
AUX_NAMES = ["money_lead@20", "invested_lead@20",
             "board_roi@20", "shed_frac@20"]


_CACHE = {}


def load():
    """The fitted search-outcome head. Same architecture as the spatial one --
    only the LABELS differ, which is the whole point of the comparison."""
    if "net" in _CACHE:
        return _CACHE["net"]
    import torch
    from tools.value_spatial import build_net
    d = np.load(MODEL)
    meta = ("C", "nu", "width", "blocks", "n_aux")
    net = build_net(int(d["C"]), int(d["nu"]), int(d["width"]),
                    int(d["blocks"]), int(d["n_aux"]) if "n_aux" in d else 0)
    net.load_state_dict({k: torch.from_numpy(d[k]) for k in d.files
                         if k not in meta and k != "aux_names"})
    net.eval()
    _CACHE["net"] = net
    return net


def value(net, obs, seat, private, unit_idx=0):
    import torch
    import tools.board_tensor as bt
    t = bt.board_pair_units(obs, seat, private=private)[None]
    u = bt.unit_state(obs, seat, unit_idx, private)[None]
    with torch.no_grad():
        return float(torch.sigmoid(net(torch.from_numpy(t.astype("float32")),
                                       torch.from_numpy(u.astype("float32")))))


def job(spec):
    """One branch point -> up to K played-out counterfactuals from one state."""
    seed, step_at, k, agent_name, opp_name = spec
    sys.path.insert(0, REPO)
    import tools.fast_env as fast_env
    fast_env.install()
    from kaggle_environments import make
    import tools.board_tensor as bt
    from tools.action_space import legal_ops, legal_qty, to_action, OPS, QTY
    import tools.early_metrics as em
    import tools.phase_metrics as pmx

    def load(n):
        g = {}
        exec(open(f"{REPO}/arena/agents/{n}/main.py").read(), g)
        return g["agent"]

    def runup(stop):
        """Fresh env AND fresh agents, replayed from step 0 -- see module doc."""
        a0, a1 = load(agent_name), load(opp_name)
        e = make("kaggriculture", configuration={"seed": seed}, debug=False)
        e.reset(2)
        while not e.done and e.state[0].observation["step"] < stop:
            o = e.state[0].observation
            e.step([a0(o), a1(e.state[1].observation)])
        return e, a0, a1

    probe, pa0, _ = runup(step_at)
    if probe.done:
        return None
    o = probe.state[0].observation
    priv = o.private
    base_act = pa0(o)
    m = legal_ops(o, 0, 0, priv)
    legal = [i for i, ok in enumerate(m) if ok]
    if len(legal) < 2:
        return None
    rng = np.random.default_rng(seed * 7919 + step_at)
    cur = (base_act.get("farmer") or ["PASS"])[0]
    # always include the policy's OWN action, so every pair contains the
    # decision the heuristic actually makes -- that is the comparison an
    # override rule has to win
    others = [i for i in legal if OPS[i].split(":")[0] != cur]
    rng.shuffle(others)
    chosen = others[: max(0, k - 1)]
    if not chosen:
        return None

    out = []
    for slot, op_i in enumerate([None] + list(chosen)):
        e, a0, a1 = runup(step_at)
        if e.done:
            return None
        oo = e.state[0].observation
        act = dict(a0(oo))
        if op_i is not None:
            opn = OPS[op_i]
            q = 1
            # signature is (obs, seat, unit_idx, op_name, private) -- passing
            # private into the op_name slot hands a Struct to .split()
            qm = legal_qty(oo, 0, 0, opn, oo.private)
            qlegal = [QTY[i] for i, ok in enumerate(qm) if ok]
            if qlegal:
                q = int(rng.choice(qlegal))
            act["farmer"] = to_action(opn, q)
        e.step([act, a1(e.state[1].observation)])
        s = e.state[0].observation
        pv = s.private
        T = bt.board_pair_units(s, 0, private=pv).astype("float16")
        U = bt.unit_state(s, 0, 0, pv).astype("float16")
        # AUXILIARY TARGETS, captured DURING the playout. They must be FUTURE
        # values: the trunk already sees today's board, so predicting today's
        # melon_tiles is trivial and teaches nothing. Day 20 is where
        # propagation measured money_lead becoming decisive (r 0.699).
        aux = None
        while not e.done:
            s2 = e.state[0].observation
            if aux is None and s2["step"] >= AUX_DAY * 24:
                p2 = s2.private
                ef = em.features(s2, 0, p2)
                mf = pmx.mid_features(s2, 0, p2)
                aux = np.array([ef[em.NAMES.index("money_lead")],
                                ef[em.NAMES.index("invested_lead")],
                                mf[pmx.MID_NAMES.index("board_roi")],
                                ef[em.NAMES.index("shed_frac")]], "float32")
            e.step([a0(s2), a1(e.state[1].observation)])
        if aux is None:          # branch already past day 20
            s2 = e.state[0].observation
            p2 = s2.private
            ef = em.features(s2, 0, p2)
            mf = pmx.mid_features(s2, 0, p2)
            aux = np.array([ef[em.NAMES.index("money_lead")],
                            ef[em.NAMES.index("invested_lead")],
                            mf[pmx.MID_NAMES.index("board_roi")],
                            ef[em.NAMES.index("shed_frac")]], "float32")
        fin0, fin1 = e.state[0].reward, e.state[1].reward
        out.append((T, U, float(fin0 > fin1), float(fin0 - fin1),
                    0 if op_i is None else 1,
                    -1 if op_i is None else int(op_i), aux))
    return (step_at // 24, out)


def build(args):
    import tools.board_tensor as bt
    rng = np.random.default_rng(args.seed)
    specs = []
    for i in range(args.n):
        # days 2-26: before day 2 almost nothing is legal, after 26 the
        # remaining game is too short for an action to matter
        step = int(rng.integers(2 * 24, 26 * 24))
        specs.append((args.base_seed + i, step, args.k, args.agent, args.opp))

    cap = args.n * args.k
    shape = (cap, bt.N_PAIR_U, 10, 10)
    print(f"{args.n} branch points x up to {args.k} played-out branches\n"
          f"  each branch REPLAYS from step 0 (agent carries mid-game state)\n"
          f"  reserving {np.prod(shape) * 2 / 1e9:.2f} GB on disk (mmap) ...",
          flush=True)
    T = np.lib.format.open_memmap(TENS, mode="w+", dtype="float16",
                                  shape=shape)
    U, Y, M, B, D, IS_ALT, OPI, AUX = [], [], [], [], [], [], [], []
    cur = nb = 0
    with mp.Pool(args.procs, maxtasksperchild=8) as pool:
        for res in pool.imap_unordered(job, specs):
            if not res:
                continue
            day, rows = res
            for (t, u, y, mg, isalt, opi, aux) in rows:
                T[cur] = t
                U.append(u); Y.append(y); M.append(mg)
                B.append(nb); D.append(day)
                IS_ALT.append(isalt); OPI.append(opi); AUX.append(aux)
                cur += 1
            nb += 1
            if nb % 100 == 0:
                print(f"  {nb}/{args.n} branch points, {cur:,} playouts",
                      flush=True)
    T.flush(); del T
    Y = np.asarray(Y, "float32"); M = np.asarray(M, "float32")
    B = np.asarray(B, "int32")
    np.savez_compressed(DATA, U=np.asarray(U, "float16"), Y=Y, M=M, B=B,
                        D=np.asarray(D, "int16"),
                        IS_ALT=np.asarray(IS_ALT, "int8"),
                        OPI=np.asarray(OPI, "int16"),
                        AUX=np.asarray(AUX, "float32"),
                        aux_names=np.array(AUX_NAMES), n=cur)
    # how much ORDERING signal does this actually contain?
    npair = wins = ties = 0
    for b in np.unique(B):
        ix = np.where(B == b)[0]
        for i in range(len(ix)):
            for j in range(i + 1, len(ix)):
                npair += 1
                if M[ix[i]] == M[ix[j]]:
                    ties += 1
                if Y[ix[i]] != Y[ix[j]]:
                    wins += 1
    print(f"\n{cur:,} playouts from {nb} branch points   "
          f"{os.path.getsize(TENS) / 1e9:.2f} GB")
    print(f"  {npair:,} within-branch pairs")
    print(f"  margin ties (no ordering signal): {ties:,} "
          f"= {100 * ties / max(npair, 1):.1f}%")
    print(f"  pairs where the WIN flips:        {wins:,} "
          f"= {100 * wins / max(npair, 1):.1f}%")
    print(f"  mean |margin| spread within a branch point: "
          f"${np.mean([np.ptp(M[np.where(B == b)[0]]) for b in np.unique(B)]):,.0f}")


def _pairs(B, V):
    """Within-branch-point pairs where V actually differs, so the pair carries
    an ordering signal. Pass M for margin pairs, Y for win-flipping pairs."""
    out = []
    for b in np.unique(B):
        ix = np.where(B == b)[0]
        for i in range(len(ix)):
            for j in range(i + 1, len(ix)):
                if V[ix[i]] != V[ix[j]]:
                    out.append((ix[i], ix[j]))
    return np.asarray(out, "int64")


def fit(args):
    """Two training criteria, in order: MARGIN to warm up, then WIN.

    They are not interchangeable and neither works alone.

      MARGIN is the SHAPING signal. It is dense -- 73.6% of within-branch
      pairs have different final margins -- and it is correlated with
      winning, so it drags the trunk to a useful representation quickly.
      It is also the WRONG objective to finish on: the recorded lesson here
      is that rating is win-based and "every executor lever moves the size
      of a LOSS". A margin-ordered head will happily prefer the action that
      loses by less.

      WIN is the SCORING signal. It is what rating measures, and it is
      sparse -- only 13.2% of pairs flip the win, so from a cold start most
      of the gradient would land on 13% of the data.

    So: warm up on margin, then switch. Model selection switches with the
    loss -- selecting on margin while training on win would hand back a
    checkpoint optimised for the objective we just abandoned.
    """
    import torch
    import torch.nn as nn
    from tools.value_spatial import build_net

    d = np.load(DATA)
    U, Y, M, B, D = d["U"], d["Y"], d["M"], d["B"], d["D"]
    T = np.load(TENS, mmap_mode="r")[: int(d["n"])]

    # split BY BRANCH POINT: playouts from one state share a world and a
    # run-up, so a per-sample split would leak outright
    bids = np.unique(B)
    rng = np.random.default_rng(args.seed)
    rng.shuffle(bids)
    va = np.isin(B, bids[: max(1, len(bids) // 5)])
    g_tr, g_va = np.where(~va)[0], np.where(va)[0]

    def remap(pairs, g):
        return (np.stack([g[pairs[:, 0]], g[pairs[:, 1]]], 1)
                if len(pairs) else pairs.reshape(0, 2))

    mtr = remap(_pairs(B[~va], M[~va]), g_tr)
    mva = remap(_pairs(B[va], M[va]), g_va)
    wtr = remap(_pairs(B[~va], Y[~va]), g_tr)
    wva = remap(_pairs(B[va], Y[va]), g_va)
    nb_va = len(set(B[va].tolist()))
    print(f"{len(T):,} playouts, {len(bids)} branch points   "
          f"train {(~va).sum():,} / val {va.sum():,}  (split BY BRANCH POINT)")
    print(f"  MARGIN pairs: train {len(mtr):,}  val {len(mva):,}")
    print(f"  WIN    pairs: train {len(wtr):,}  val {len(wva):,}"
          f"   ({100*len(wtr)/max(len(mtr),1):.0f}% as many -- the sparsity"
          f" the warm-up exists to get past)")
    print(f"  held-out BRANCH POINTS: {nb_va}  <- the effective n, not the"
          f" pair count")

    AUX = d["AUX"] if "AUX" in d else None
    n_aux = AUX.shape[1] if AUX is not None and args.aux > 0 else 0
    if n_aux:
        # z-score: the four targets have different units, and an unscaled MSE
        # would let whichever has the largest variance dominate the gradient
        mu, sd = AUX.mean(0), AUX.std(0) + 1e-6
        AUXn = ((AUX - mu) / sd).astype("float32")
        print(f"  AUX targets ({args.aux:g} weight): "
              f"{[str(x) for x in d['aux_names']]}")
    net = build_net(T.shape[1], U.shape[1], args.width, args.blocks, n_aux)
    opt = torch.optim.Adam(net.parameters(), lr=args.lr,
                           weight_decay=args.wd)
    bce = nn.BCEWithLogitsLoss()
    Yt = torch.from_numpy(Y)

    def batch(ix):
        return (torch.from_numpy(np.asarray(T[ix], dtype="float32")),
                torch.from_numpy(U[ix].astype("float32")))

    def logits(ix, bs=512):
        outs = []
        for i in range(0, len(ix), bs):
            x, u = batch(np.sort(ix[i: i + bs]))
            outs.append(net(x, u))
        return torch.cat(outs)

    def sign_acc(pairs, target):
        """Does V order the pair the way the PLAYOUT did?"""
        if not len(pairs):
            return float("nan")
        flat = np.unique(pairs.ravel())
        pos = {v: i for i, v in enumerate(flat)}
        with torch.no_grad():
            lg = logits(flat).numpy()
        a = np.array([lg[pos[i]] for i, _ in pairs])
        b = np.array([lg[pos[j]] for _, j in pairs])
        return float(np.mean(np.sign(a - b)
                             == np.sign(target[pairs[:, 0]]
                                        - target[pairs[:, 1]])))

    def epoch(pairs, target, pointwise_w):
        net.train()
        perm = np.random.default_rng(len(pairs)).permutation(len(pairs))
        for i in range(0, len(pairs), args.batch):
            pb = pairs[perm[i: i + args.batch]]
            ia, ib = pb[:, 0], pb[:, 1]
            xa, ua = batch(ia)
            xb, ub = batch(ib)
            if n_aux:
                la, aa = net.both(xa, ua)
                lb, ab = net.both(xb, ub)
            else:
                la, lb = net(xa, ua), net(xb, ub)
            # RankNet / Bradley-Terry: the logit DIFFERENCE must carry the
            # sign of the played-out difference. This is the only term
            # trained on a counterfactual.
            tgt = torch.from_numpy((target[ia] > target[ib]).astype("float32"))
            loss = bce(la - lb, tgt)
            if pointwise_w > 0:
                loss = loss + pointwise_w * 0.5 * (
                    bce(la, Yt[ia]) + bce(lb, Yt[ib]))
            if n_aux:
                ta = torch.from_numpy(AUXn[ia])
                tb = torch.from_numpy(AUXn[ib])
                loss = loss + args.aux * 0.5 * (
                    ((aa - ta) ** 2).mean() + ((ab - tb) ** 2).mean())
            opt.zero_grad()
            loss.backward()
            opt.step()

    se = np.sqrt(0.25 / max(nb_va, 1))
    hist = {}
    best_state = None
    print(f"\n  {'ep':>4}{'phase':>9}{'margin acc':>13}{'win acc':>10}")
    for phase, (pairs, target, nep, sel_pairs, sel_tgt, sel_name) in enumerate((
            (mtr, M, args.warmup, mva, M, "margin"),
            (wtr, Y, args.epochs - args.warmup, wva, Y, "win"))):
        if not len(pairs):
            print(f"  phase {phase}: no usable pairs, skipped")
            continue
        best, bad = -1.0, 0
        for e in range(nep):
            epoch(pairs, target, args.alpha)
            net.eval()
            ma = sign_acc(mva, M)
            wa = sign_acc(wva, Y)
            cur = sign_acc(sel_pairs, sel_tgt)
            tag = "warmup" if phase == 0 else "WIN"
            if e % 2 == 0 or bad >= args.patience - 1:
                print(f"  {e:>4}{tag:>9}{ma:>13.3f}{wa:>10.3f}", flush=True)
            if cur > best + 1e-4:
                best, bad = cur, 0
                best_state = {k: v.clone() for k, v in net.state_dict().items()}
            else:
                bad += 1
            if bad >= args.patience:
                break
        hist[sel_name] = best
        # carry the warm-up's best weights into the win phase
        if best_state is not None:
            net.load_state_dict(best_state)
        print(f"  -> best {sel_name} sign accuracy {best:.3f}")

    np.savez_compressed(MODEL, C=T.shape[1], nu=U.shape[1], width=args.width,
                        blocks=args.blocks, n_aux=n_aux,
                        **{k: v.numpy() for k, v in net.state_dict().items()})
    net.eval()
    fin_m, fin_w = sign_acc(mva, M), sign_acc(wva, Y)
    print(f"\n  FINAL HEAD, held-out ({nb_va} branch points, se {se:.3f}):")
    print(f"     margin sign accuracy {fin_m:.3f}   "
          f"z = {(fin_m - 0.5)/se:+.2f}")
    print(f"     WIN    sign accuracy {fin_w:.3f}   "
          f"z = {(fin_w - 0.5)/se:+.2f}   <- the criterion that scores")
    print(f"\n  baselines on the same statistic (corpus labels):")
    print(f"     aggregate head  0.609 +/- 0.072  (n=46, selected subset)")
    print(f"     spatial   head  0.455 +/- 0.042  (n=143)")
    print(f"  -> {MODEL}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["build", "fit"])
    ap.add_argument("--n", type=int, default=1200)
    ap.add_argument("--k", type=int, default=4)
    ap.add_argument("--procs", type=int, default=6)
    ap.add_argument("--seed", type=int, default=17)
    ap.add_argument("--base-seed", type=int, default=600_000)
    ap.add_argument("--agent", default="champ-h8")
    ap.add_argument("--opp", default="champ-h8")
    ap.add_argument("--epochs", type=int, default=40)
    ap.add_argument("--batch", type=int, default=128)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--wd", type=float, default=1e-4)
    ap.add_argument("--width", type=int, default=64)
    ap.add_argument("--blocks", type=int, default=3)
    ap.add_argument("--patience", type=int, default=8)
    ap.add_argument("--alpha", type=float, default=0.3,
                    help="weight on the pointwise win-label term")
    ap.add_argument("--aux", type=float, default=0.3,
                    help="weight on the AUXILIARY forecast head (0 disables). "
                         "Targets are FUTURE values at day 20 -- the trunk "
                         "already sees today's board.")
    ap.add_argument("--warmup", type=int, default=10,
                    help="epochs on the MARGIN criterion before switching "
                         "to WIN")
    args = ap.parse_args()
    (build if args.cmd == "build" else fit)(args)


if __name__ == "__main__":
    main()
