# LP assembly
# --------------------------------------------------------------------------

class LP:
    """Sparse LP builder: minimise c @ x s.t. A_ub @ x <= b_ub, A_eq @ x == b_eq."""

    def __init__(self):
        self.cost = []
        self.lo = []
        self.hi = []
        self.names = []
        self.ub = ([], [], [], [], [])   # i, j, v, rhs, names
        self.eq = ([], [], [], [], [])

    def var(self, name, cost=0.0, lo=0.0, hi=None):
        self.cost.append(cost)
        self.lo.append(lo)
        self.hi.append(hi)
        self.names.append(name)
        return len(self.cost) - 1

    def _add(self, store, name, terms, rhs):
        i, j, v, b, names = store
        r = len(b)
        for col, coef in terms:
            if coef:
                i.append(r)
                j.append(col)
                v.append(float(coef))
        b.append(float(rhs))
        names.append(name)

    def row(self, name, terms, rhs):
        self._add(self.ub, name, terms, rhs)

    def eqrow(self, name, terms, rhs):
        self._add(self.eq, name, terms, rhs)

    @property
    def row_names(self):
        return self.ub[4]

    def _matrix(self, store):
        i, j, v, b, _ = store
        if not b:
            return None, None
        A = coo_matrix((v, (i, j)), shape=(len(b), len(self.cost))).tocsr()
        return A, np.array(b)

    def _linprog(self, bounds):
        A_ub, b_ub = self._matrix(self.ub)
        A_eq, b_eq = self._matrix(self.eq)
        return linprog(np.array(self.cost), A_ub=A_ub, b_ub=b_ub,
                       A_eq=A_eq, b_eq=b_eq, bounds=bounds, method="highs")

    def solve(self, integral=None):
        """Solve, optionally forcing `integral` columns to whole numbers.

        MILP gives no duals, so when integrality is requested the discrete
        columns are solved first, then pinned and the LP re-solved -- same
        objective, but with the shadow prices that say what is binding.
        """
        bounds = list(zip(self.lo, self.hi))
        if not integral:
            return self._linprog(bounds)

        from scipy.optimize import milp, LinearConstraint, Bounds

        n = len(self.cost)
        cons = []
        A_ub, b_ub = self._matrix(self.ub)
        if A_ub is not None:
            cons.append(LinearConstraint(A_ub, -np.inf, b_ub))
        A_eq, b_eq = self._matrix(self.eq)
        if A_eq is not None:
            cons.append(LinearConstraint(A_eq, b_eq, b_eq))
        lo = np.array([v if v is not None else -np.inf for v in self.lo])
        hi = np.array([v if v is not None else np.inf for v in self.hi])
        integrality = np.zeros(n)
        integrality[list(integral)] = 1
        r = milp(np.array(self.cost), constraints=cons, integrality=integrality,
                 bounds=Bounds(lo, hi))
        if not r.success:
            raise RuntimeError(f"MILP failed: {r.message}")

        for j in integral:                      # pin and re-solve for duals
            v = float(np.round(r.x[j]))
            bounds[j] = (v, v)
        return self._linprog(bounds)


def build_and_solve(eff, shops=None, opp_schedule=None, wheat_buy_price=45.0,
                    fert_buy_price=100.0, max_hands=MAX_HIRE_BRACKETS,
                    integral_land=True, verbose=True):
    acts = build_activities()
    drain = cumulative_drain(shops)

    # The opponent's supply arrives over the season, exactly as ours does.
    cum_opp = {}
    for p in PRODUCTS:
        per_day = (opp_schedule or {}).get(p, [0.0] * DAYS)
        run, cum = 0.0, []
        for d in range(DAYS):
            run += per_day[d]
            cum.append(run)
        cum_opp[p] = cum

    caps, bandprice = {}, {}
    for p in PRODUCTS:
        caps[p], bandprice[p] = revenue_bands(p, drain[p], cum_opp[p])

    lp = LP()

    # --- columns -----------------------------------------------------------
    # Costs and revenues are carried by the cash-flow equality, not the
    # objective, so every column here is cost-free.
    act_vars = [lp.var(a["label"]) for a in acts]

    hire_vars = {}
    for d in range(DAYS):
        for b in range(max_hands):
            hire_vars[(d, b)] = lp.var(f"hire/d{d}/b{b}", hi=1.0)

    land_vars = {}
    for j in range(len(LAND_PRICES)):
        for d in range(DAYS):
            land_vars[(j, d)] = lp.var(f"land{j}/d{d}", hi=1.0)

    sell_vars = {}
    for p in PRODUCTS:
        for j in range(len(caps[p])):
            for d in range(DAYS):
                sell_vars[(p, j, d)] = lp.var(f"sell/{p}/s{j}/d{d}")

    wbuy = {d: lp.var(f"wbuy/d{d}") for d in range(DAYS)}
    fbuy = {d: lp.var(f"fbuy/d{d}") for d in range(DAYS)}

    # State variables: bank balance and per-product shed stock, carried day to
    # day. Keeping them as columns turns every cumulative constraint into a
    # sparse one-day flow instead of an O(days^2) dense row.
    cash = {d: lp.var(f"cash/d{d}") for d in range(DAYS)}
    stock = {(p, d): lp.var(f"stock/{p}/d{d}") for p in PRODUCTS for d in range(DAYS)}

    # Objective: maximise the closing bank.
    lp.cost[cash[LAST_DAY]] = -1.0

    # --- precompute per-day aggregates -------------------------------------
    # tiles(d), labour(d), yield(p, d), fert_use(d), fert_out(d), wheat_use(d)
    for d in range(DAYS):
        # Tiles: occupancy <= 25 * (1 + land bought by day d)
        terms = [(act_vars[i], 1.0) for i, a in enumerate(acts)
                 if d in a["occupancy_set"]]
        for j in range(len(LAND_PRICES)):
            for e in range(d + 1):
                terms.append((land_vars[(j, e)], -float(TILES_PER_QUAD)))
        lp.row(f"tiles/d{d}", terms, TILES_PER_QUAD)

        # Labour: actions <= 24 * eff * (1 + hands)
        cap_per_unit = TURNS_PER_DAY * eff
        terms = [(act_vars[i], a["labour"][d]) for i, a in enumerate(acts) if d in a["labour"]]
        for b in range(max_hands):
            terms.append((hire_vars[(d, b)], -cap_per_unit))
        lp.row(f"labour/d{d}", terms, cap_per_unit)

    # Land must be bought in order, and each parcel at most once.
    for j in range(len(LAND_PRICES)):
        lp.row(f"land{j}/once", [(land_vars[(j, d)], 1.0) for d in range(DAYS)], 1.0)
        if j > 0:
            for d in range(DAYS):
                terms = [(land_vars[(j, e)], 1.0) for e in range(d + 1)]
                terms += [(land_vars[(j - 1, e)], -1.0) for e in range(d + 1)]
                lp.row(f"land{j}/order/d{d}", terms, 0.0)

    # Cash flow: cash[d] = cash[d-1] + sales - spending, with cash >= 0 by
    # its variable bound. cash[-1] is the opening balance.
    for d in range(DAYS):
        terms = [(cash[d], 1.0)]
        if d:
            terms.append((cash[d - 1], -1.0))
        for i, a in enumerate(acts):
            if a["cost_day"] == d:
                terms.append((act_vars[i], a["cost"]))
        for b in range(max_hands):
            terms.append((hire_vars[(d, b)], float(fib(b))))
        for j in range(len(LAND_PRICES)):
            terms.append((land_vars[(j, d)], float(LAND_PRICES[j])))
        terms.append((wbuy[d], wheat_buy_price))
        terms.append((fbuy[d], fert_buy_price))
        for p in PRODUCTS:
            for jseg in range(len(caps[p])):
                terms.append((sell_vars[(p, jseg, d)], -bandprice[p][jseg][d]))
        lp.eqrow(f"cashflow/d{d}", terms, START_MONEY if d == 0 else 0.0)

    # Product stock: what is produced but not yet sold sits in the shed, so
    # nothing can be sold before it exists.
    for p in PRODUCTS:
        for d in range(DAYS):
            terms = [(stock[(p, d)], 1.0)]
            if d:
                terms.append((stock[(p, d - 1)], -1.0))
            for jseg in range(len(caps[p])):
                terms.append((sell_vars[(p, jseg, d)], 1.0))
            for i, a in enumerate(acts):
                coef = 0.0
                coef -= a["yield"].get(p, {}).get(d, 0.0)
                if p == "FERTILIZER":
                    coef -= a.get("fert_out", {}).get(d, 0.0)
                    coef += a["fert_use"].get(d, 0.0)
                if p == "WHEAT":
                    coef += a["wheat_use"].get(d, 0.0)
                if coef:
                    terms.append((act_vars[i], coef))
            if p == "WHEAT":
                terms.append((wbuy[d], -1.0))
            if p == "FERTILIZER":
                terms.append((fbuy[d], -1.0))
            lp.eqrow(f"stockflow/{p}/d{d}", terms, 0.0)

    # Price bands must be walked DOWN in order: a band may be filled only in
    # proportion to how full the band above it already is, at every point in
    # the season. Without this the LP sells a cheap band early and a dear one
    # late, collecting prices no real sale order can produce.
    fill = {}
    for p in PRODUCTS:
        for j, cap in enumerate(caps[p]):
            for d in range(DAYS):
                fill[(p, j, d)] = lp.var(f"fill/{p}/s{j}/d{d}", hi=cap)
    for p in PRODUCTS:
        for j, cap in enumerate(caps[p]):
            for d in range(DAYS):
                terms = [(fill[(p, j, d)], 1.0), (sell_vars[(p, j, d)], -1.0)]
                if d:
                    terms.append((fill[(p, j, d - 1)], -1.0))
                lp.eqrow(f"fillflow/{p}/{j}/d{d}", terms, 0.0)
                if j:
                    lp.row(f"order/{p}/{j}/d{d}",
                           [(fill[(p, j, d)], 1.0 / cap),
                            (fill[(p, j - 1, d)], -1.0 / caps[p][j - 1])], 0.0)

    # Shed holds at most 100 non-seed items overnight.
    for d in range(DAYS):
        lp.row(f"shed/d{d}", [(stock[(p, d)], 1.0) for p in PRODUCTS], SHED_CAP)

    integral = sorted(land_vars.values()) if integral_land else None
    res = lp.solve(integral)
    if not res.success:
        raise RuntimeError(f"LP failed: {res.message}")

    return _report(lp, res, acts, act_vars, hire_vars, land_vars, sell_vars,
                   caps, bandprice, drain, opp_schedule or {}, eff, max_hands,
                   verbose)


def _report(lp, res, acts, act_vars, hire_vars, land_vars, sell_vars,
            caps, bandprice, drain, opp_schedule, eff, max_hands, verbose):
    x = res.x
    final = -res.fun          # objective is -cash[LAST_DAY]
    duals = res.ineqlin.marginals if hasattr(res, "ineqlin") else None

    out = {"final": final, "eff": eff}

    # Revenue and volume by product.
    rev, vol, sched = {}, {}, {}
    for p in PRODUCTS:
        r = v = 0.0
        per_day = [0.0] * DAYS
        for jseg in range(len(caps[p])):
            for d in range(DAYS):
                q = x[sell_vars[(p, jseg, d)]]
                r += q * bandprice[p][jseg][d]
                v += q
                per_day[d] += q
        rev[p], vol[p], sched[p] = r, v, per_day
    out["revenue"], out["volume"], out["sell_schedule"] = rev, vol, sched

    # Honest replay: push this schedule (and the opponent's) through the
    # engine's own inventory recursion, giving the seller every benefit of the
    # doubt -- the whole day's town drain lands before the day's sales.
    replay = {}
    for p in PRODUCTS:
        inv = float(MARKET_PARAMS[p]["I0"])
        got = 0.0
        prev_drain = 0.0
        opp = opp_schedule.get(p, [0.0] * DAYS)
        for d in range(DAYS):
            inv -= drain[p][d] - prev_drain
            prev_drain = drain[p][d]
            q = sched[p][d]
            whole, frac = int(q), q - int(q)
            if whole:
                prices = econ.sell_marginal_prices(p, int(round(inv)), whole)
                got += sum(prices)
                inv += sum(1 for pr in prices if pr > 1)
            if frac > 1e-9:
                got += frac * econ.price(p, int(round(inv)))
                inv += frac
            inv += opp[d]          # the opponent's supply lands too
        replay[p] = got
    out["replay"] = replay

    # Chosen plan.
    plan = defaultdict(float)
    plant_days = defaultdict(list)
    for i, a in enumerate(acts):
        q = x[act_vars[i]]
        if q > 1e-6:
            key = a["label"].split("/")[0]
            plan[key] += q
            plant_days[key].append((a["cost_day"], q, a["label"]))
    out["plan"] = dict(plan)
    out["plant_days"] = plant_days

    hands = [sum(x[hire_vars[(d, b)]] for b in range(max_hands)) for d in range(DAYS)]
    out["hands"] = hands
    land_day = {}
    for j in range(len(LAND_PRICES)):
        for d in range(DAYS):
            if x[land_vars[(j, d)]] > 1e-6:
                land_day[j] = (d, x[land_vars[(j, d)]])
    out["land"] = land_day

    # Binding constraints via shadow prices.
    if duals is not None:
        shadow = defaultdict(float)
        for r, name in enumerate(lp.row_names):
            kind = name.split("/")[0]
            shadow[kind] += abs(duals[r])
        out["shadow"] = dict(shadow)
        out["labour_duals"] = [
            -duals[lp.row_names.index(f"labour/d{d}")] for d in range(DAYS)
        ]
        out["tile_duals"] = [
            -duals[lp.row_names.index(f"tiles/d{d}")] for d in range(DAYS)
        ]

    if verbose:
        _print_report(out, caps, bandprice, drain)
    return out


def _print_report(out, caps, bandprice, drain):
    print(f"\n{'='*74}")
    print(f"LP UPPER BOUND   labour efficiency {out['eff']:.3f}"
          f"   ->   FINAL BANK  ${out['final']:,.0f}")
    print("=" * 74)

    print(f"\n{'product':<12} {'units':>8} {'revenue':>11} {'$/unit':>8} "
          f"{'drain':>8} {'replayed':>11} {'mkt cap $':>11}")
    tot_rev = tot_cap = tot_replay = 0.0
    for p in PRODUCTS:
        v, r = out["volume"][p], out["revenue"][p]
        # Best case for this product alone: every band sold on the last day.
        cap = sum(c * bandprice[p][j][LAST_DAY] for j, c in enumerate(caps[p]))
        rp = out["replay"][p]
        tot_rev += r
        tot_cap += cap
        tot_replay += rp
        print(f"{p:<12} {v:>8,.0f} {r:>11,.0f} {r/max(v,1e-9):>8,.0f} "
              f"{drain[p][LAST_DAY]:>8,.0f} {rp:>11,.0f} {cap:>11,.0f}")
    print(f"{'TOTAL':<12} {'':>8} {tot_rev:>11,.0f} {'':>8} {'':>8} "
          f"{tot_replay:>11,.0f} {tot_cap:>11,.0f}")
    gap = tot_rev - tot_replay
    print(f"\nladder over-credit vs exact engine replay of the same schedule: "
          f"${gap:,.0f} ({gap/max(tot_rev,1e-9)*100:.1f}%)")
    print(f"\nmarket absorption ceiling (sell every band at the best day's price, "
          f"no labour/tile/cash limit): ${tot_cap:,.0f}")

    print("\nplan (tile-plantings / animals, and the variants chosen):")
    for k, v in sorted(out["plan"].items(), key=lambda kv: -kv[1]):
        variants = defaultdict(float)
        for _, q, label in out["plant_days"][k]:
            parts = label.split("/")
            tag = "/".join(p for p in parts[1:] if not p.startswith("d")) or "plain"
            variants[tag] += q
        vs = "  ".join(f"{t} {q:.0f}" for t, q in
                       sorted(variants.items(), key=lambda kv: -kv[1]))
        print(f"  {k:<12} {v:>7.1f}   {vs}")
    print("     (aN = harvested at age N, F = fertilized, C = cared for daily)")
    print(f"  hands/day   min {min(out['hands']):.1f}  mean "
          f"{sum(out['hands'])/DAYS:.1f}  max {max(out['hands']):.1f}")
    if out["land"]:
        for j, (d, q) in sorted(out["land"].items()):
            print(f"  land #{j+1} bought day {d} (x{q:.2f})")

    if "labour_duals" in out:
        ld, td = out["labour_duals"], out["tile_duals"]
        print(f"\nshadow prices ($ per extra unit of capacity, by day):")
        print(f"  labour: mean {sum(ld)/DAYS:>7,.1f}  max {max(ld):>8,.1f} "
              f"(day {ld.index(max(ld))})   -> $ per extra ACTION")
        print(f"  tiles : mean {sum(td)/DAYS:>7,.1f}  max {max(td):>8,.1f} "
              f"(day {td.index(max(td))})   -> $ per extra TILE-DAY")
        binding = [d for d in range(DAYS) if ld[d] > 1.0]
        print(f"  labour binds on {len(binding)}/{DAYS} days"
              f"{' (' + str(binding[0]) + '..' + str(binding[-1]) + ')' if binding else ''}")
        binding_t = [d for d in range(DAYS) if td[d] > 1.0]
        print(f"  tiles  bind on {len(binding_t)}/{DAYS} days"
              f"{' (' + str(binding_t[0]) + '..' + str(binding_t[-1]) + ')' if binding_t else ''}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--eff", type=float, default=None,
                    help="productive actions per worker-turn (default: sweep-free run at ours)")
    ap.add_argument("--shops", default=None,
                    help="comma-separated shop list open all season (default: expected draw)")
    ap.add_argument("--mirror", type=int, nargs="?", const=4, default=0,
                    metavar="N",
                    help="iterate against an opponent who sells what we sold, "
                         "N rounds, towards a symmetric fixed point")
    ap.add_argument("--sweep", action="store_true", help="sweep labour efficiency")
    ap.add_argument("--max-hands", type=int, default=MAX_HIRE_BRACKETS)
    args = ap.parse_args()

    shops = args.shops.split(",") if args.shops else None

    if args.sweep:
        head = "final bank" if not args.mirror else "solo    vs mirrored opponent"
        print(f"\n{'eff':>6} {'hands/day':>10}   {head}")
        for eff in (1.0, 0.75, EFF_LEADERS, EFF_OURS, 0.35, 0.30):
            r = build_and_solve(eff, shops, max_hands=args.max_hands, verbose=False)
            solo, hands = r["final"], sum(r["hands"]) / DAYS
            mirrored = ""
            if args.mirror:
                history = [r["sell_schedule"]]
                for _ in range(args.mirror):
                    sched = {p: [sum(h[p][d] for h in history) / len(history)
                                 for d in range(DAYS)] for p in PRODUCTS}
                    r = build_and_solve(eff, shops, opp_schedule=sched,
                                        max_hands=args.max_hands, verbose=False)
                    history.append(r["sell_schedule"])
                mirrored = f"   ${r['final']:>10,.0f}"
            tag = ""
            if abs(eff - EFF_OURS) < 1e-6:
                tag = "   <- ours (measured)"
            if abs(eff - EFF_LEADERS) < 1e-6:
                tag = "   <- top meta (measured)"
            print(f"{eff:>6.3f} {hands:>10.1f}   ${solo:>10,.0f}{mirrored}{tag}")
        return

    eff = args.eff if args.eff is not None else EFF_OURS

    if args.mirror:
        # Iterated best response against a mirror of ourselves. Round 0 is the
        # solo bound (opponent sells nothing); each later round prices our
        # sales into a market the opponent is supplying on the same timetable.
        print(f"\niterating {args.mirror} rounds of symmetric best response "
              f"at eff {eff:.3f}\n")
        print(f"{'round':>6} {'final bank':>13}   dominant products")
        sched, history = None, []
        for r in range(args.mirror + 1):
            res = build_and_solve(eff, shops, opp_schedule=sched,
                                  max_hands=args.max_hands, verbose=False)
            top = sorted(res["revenue"].items(), key=lambda kv: -kv[1])[:4]
            top = ", ".join(f"{k.lower()} ${v/1000:.0f}k" for k, v in top if v > 500)
            label = "solo" if r == 0 else f"mirror {r}"
            print(f"{label:>6} ${res['final']:>12,.0f}   {top}")
            # Fictitious play: the opponent supplies the AVERAGE of every plan
            # we have played so far. Best-responding to the last round alone
            # oscillates between flooding the premium ladders and fleeing them.
            history.append(res["sell_schedule"])
            sched = {p: [sum(h[p][d] for h in history) / len(history)
                         for d in range(DAYS)] for p in PRODUCTS}
        print("\nfinal round in full:")
        build_and_solve(eff, shops, opp_schedule=sched, max_hands=args.max_hands)
        return

    build_and_solve(eff, shops, max_hands=args.max_hands)


if __name__ == "__main__":
    main()
