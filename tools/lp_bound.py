def _water_days(required, last_age):
    """Minimum watering ages covering `required`, never two dry days running.

    A plant starts with consecutive_unwatered = 1 (planting day counts), so age
    0 must be watered and thereafter the gap between waters may not exceed 2.
    """
    days = sorted(set(required) | {0})
    out = []
    prev = None
    for a in days:
        if a > last_age:
            break
        while prev is not None and a - prev > 2:
            prev += 2
            out.append(prev)
        out.append(a)
        prev = a
    return sorted(set(out))


def one_time_activity(crop, plant_day, harvest_age, fert):
    """Profile for a one-time crop (wheat / carrot / melon).

    Returns None when the cycle cannot finish inside the season.
    """
    cd = CROPS[crop]
    if harvest_age < cd["first_yield_day"] or harvest_age > cd["max_yield_day"]:
        return None
    harvest_day = plant_day + harvest_age
    if harvest_day > LAST_DAY:
        return None

    window_start = (cd["max_yield_day"] + 1) // 2
    bonus_ages = [a for a in range(window_start, harvest_age + 1)]
    waters = _water_days(bonus_ages, harvest_age)

    # One FERTILIZE at the top of the bonus window covers ages ws..ws+2.
    fert_ages = [window_start] if fert else []
    fert_until = window_start + 2 if fert else -10

    units = 1  # a fresh one-time plant starts with yield_units = 1
    for a in waters:
        if window_start <= a <= cd["max_yield_day"]:
            units = min(cd["max_yield"], units + (2 if a <= fert_until else 1))

    labour = defaultdict(float)
    labour[plant_day] += 1.0                      # PLANT
    for a in waters:
        labour[plant_day + a] += 1.0              # WATER
    for a in fert_ages:
        labour[plant_day + a] += 1.0              # FERTILIZE
    labour[harvest_day] += 1.0                    # HARVEST

    fert_use = defaultdict(float)
    for a in fert_ages:
        fert_use[plant_day + a] += 1.0

    # HARVEST clears a one-time plant the moment it fires, so a later turn of
    # the same day can already replant the tile -- the harvest day is free.
    occupancy = list(range(plant_day, harvest_day))

    return {
        "label": f"{crop}/d{plant_day}/a{harvest_age}{'/F' if fert else ''}",
        "cost_day": plant_day,
        "cost": float(cd["seed"]),
        "labour": dict(labour),
        "occupancy": occupancy,
        "yield": {crop: {harvest_day: float(units)}},
        "fert_use": dict(fert_use),
        "wheat_use": {},
    }


def ongoing_activity(crop, plant_day, fert):
    """Profile for an ongoing crop (tomato / strawberry).

    Productions land at end of day `plant_day + first_yield_day - 1 + k*interval`
    and are worth 2 instead of 1 when that day was watered and fertilized.
    `max_yield` caps unharvested units on the tile, so the schedule harvests
    whenever the tile would otherwise overflow.
    """
    cd = CROPS[crop]
    first, interval, cap = cd["first_yield_day"], cd["interval"], cd["max_yield"]

    # Engine: production fires at the end of day (plant + first - 1 + k*interval).
    prod_eves = [plant_day + first - 1 + k * interval for k in range(cap)]
    prod_days = [e + 1 for e in prod_eves]        # first day the units exist
    if prod_days[0] > LAST_DAY:
        return None

    # Fertilize so that each eve day is covered: one FERTILIZE lasts 3 days.
    fert_ages, fert_windows = [], []
    if fert:
        covered = -10
        for e in prod_eves:
            if e > covered:
                fert_ages.append(e - plant_day)
                covered = e + 2
                fert_windows.append((e, e + 2))

    def fertilized(eve):
        return any(lo <= eve <= hi for lo, hi in fert_windows)

    # Water every production eve (required for the bonus), plus survival waters.
    required = [e - plant_day for e in prod_eves]
    last_age = prod_days[-1] - plant_day
    waters = _water_days(required, last_age)
    watered_days = {plant_day + a for a in waters}

    # Walk the tile: accumulate production, harvest before the cap bites.
    units_on_tile = 0.0
    harvested = defaultdict(float)
    productions = 0
    for eve, day in zip(prod_eves, prod_days):
        if eve > LAST_DAY:
            break
        gain = 2.0 if (eve in watered_days and fertilized(eve)) else 1.0
        units_on_tile = min(float(cap), units_on_tile + gain)
        productions += 1
        next_eve = prod_eves[productions] if productions < len(prod_eves) else None
        next_gain = 0.0
        if next_eve is not None and next_eve <= LAST_DAY:
            next_gain = 2.0 if (next_eve in watered_days and fertilized(next_eve)) else 1.0
        # Harvest when the next production would overflow the tile, at the end
        # of the plant's life, or at the season boundary.
        if day > LAST_DAY:
            break
        if next_eve is None or next_eve > LAST_DAY or units_on_tile + next_gain > cap:
            harvested[day] += units_on_tile
            units_on_tile = 0.0

    if not harvested:
        return None

    labour = defaultdict(float)
    labour[plant_day] += 1.0
    for a in waters:
        d = plant_day + a
        if d <= LAST_DAY:
            labour[d] += 1.0
    for a in fert_ages:
        d = plant_day + a
        if d <= LAST_DAY:
            labour[d] += 1.0
    for d in harvested:
        labour[d] += 1.0

    fert_use = defaultdict(float)
    for a in fert_ages:
        d = plant_day + a
        if d <= LAST_DAY:
            fert_use[d] += 1.0

    # Ongoing crops decay one day after the final production; the tile is held
    # until then (or until the season ends).
    end_day = min(LAST_DAY, max(harvested))
    occupancy = list(range(plant_day, end_day + 1))

    return {
        "label": f"{crop}/d{plant_day}{'/F' if fert else ''}",
        "cost_day": plant_day,
        "cost": float(cd["seed"]),
        "labour": dict(labour),
        "occupancy": occupancy,
        "yield": {crop: dict(harvested)},
        "fert_use": dict(fert_use),
        "wheat_use": {},
    }


def animal_activity(kind, place_day, care):
    """Profile for one animal placed on `place_day`.

    Setup is PICKUP + BUILD + PLACE; every later day costs FEED + COLLECT_FERT
    (+ CARE when the regime cares, + HARVEST when there is product waiting).
    CARE banks +1 per fed-and-cared day and the whole bank is paid out on the
    next scheduled production.
    """
    a = ANIMALS[kind]
    product = a["product"]
    first, interval, held = a["first_yield_day"], a["interval"], a["max_held"]
    if place_day + first > LAST_DAY:
        return None

    labour = defaultdict(float)
    wheat = defaultdict(float)
    fert = defaultdict(float)
    produced = defaultdict(float)

    labour[place_day] += 3.0            # PICKUP + BUILD_* + PLACE
    pending = 0.0
    on_tile = 0.0

    for day in range(place_day, DAYS):
        labour[day] += 1.0              # FEED
        wheat[day] += 1.0
        if care:
            labour[day] += 1.0          # CARE
        if day > place_day:
            labour[day] += 1.0          # COLLECT_FERTILIZER
            fert[day] += 1.0
            if on_tile > 0:
                labour[day] += 1.0      # HARVEST
                produced[day] += on_tile
                on_tile = 0.0
        # End-of-day refresh.
        nxt = day + 1
        since = nxt - place_day - first
        if since >= 0 and since % interval == 0:
            on_tile = min(float(held), on_tile + 1.0 + pending)
            pending = 0.0
        if care:
            pending += 1.0

    if not produced:
        return None

    return {
        "label": f"{kind}/d{place_day}{'/C' if care else ''}",
        "cost_day": place_day,
        "cost": float(a["cost"]),
        "labour": dict(labour),
        "occupancy": list(range(place_day, DAYS)),
        "yield": {product: dict(produced)},
        "fert_use": {},
        "wheat_use": dict(wheat),
        "fert_out": dict(fert),
    }


def build_activities():
    acts = []
    for crop, cd in CROPS.items():
        for d in range(DAYS):
            if cd["ongoing"]:
                for f in (0, 1):
                    act = ongoing_activity(crop, d, f)
                    if act:
                        acts.append(act)
            else:
                for age in range(cd["first_yield_day"], cd["max_yield_day"] + 1):
                    for f in (0, 1):
                        act = one_time_activity(crop, d, age, f)
                        if act:
                            acts.append(act)
    for kind in ANIMALS:
        for d in range(DAYS):
            for c in (0, 1):
                act = animal_activity(kind, d, c)
                if act:
                    acts.append(act)
    for a in acts:
        a["occupancy_set"] = set(a["occupancy"])
    return acts


