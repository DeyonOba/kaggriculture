"""LP upper bound on a season's final bank.

The question this answers: ignoring routing, weeds and the opponent's
reactions, how much money can a farm POSSIBLY make in 30 days given the four
things that actually bind -- tiles, labour, cash flow and market absorption?
If the labour-constrained optimum lands near the best replay tape ($126k) then
no planner can beat the tape and the lever is throughput; if it lands far above,
the headroom is real and a computed schedule can reach it.

MODEL
-----
An activity-based LP. One column per (crop, plant day, harvest age, fertilizer
regime), per (animal kind, placement day, care regime), per hire bracket per
day, per land parcel per day, and per (product, price segment, day) sale.

Each crop/animal column carries a per-day profile generated by SIMULATING the
engine's own yield rules (kagent.constants mirrors them; tests/test_econ_parity
keeps that honest):

  * one-time crops accrue +1 yield per WATER inside the bonus window
    [ceil(max_yield_day/2), max_yield_day], +2 if fertilizer is active, capped
    at max_yield
  * ongoing crops fire a scheduled production every `interval` days starting at
    age `first_yield_day`, worth 2 instead of 1 when the plant was watered AND
    fertilized on the preceding day; `max_yield` caps BOTH the number of
    productions and the units that may sit unharvested on the tile
  * animals pay out `1 + banked CARE days` on each scheduled production if fed,
    capped by max_held, and drop 1 fertilizer every day whatever you do

Waters are the minimum set that keeps the plant alive (never two dry days in a
row) and covers every bonus day, so the labour figure is a floor, which is what
an upper bound wants.

MARKET
------
Revenue is bounded product by product. The i-th unit we sell all season faces a
real inventory of at least

    I0 - (drain already realised) + (opponent sales so far) + (i - 1)
      >= I0 - (WHOLE SEASON's drain) + (i - 1)

and price falls with inventory, so pricing unit i at price(I0 - D_total + i - 1)
can only overstate the revenue. That makes the revenue curve concave and
day-independent -- a plain LP ladder -- while remaining a genuine upper bound.
`--credit` tightens it by crediting only part of the season drain; `--mirror`
re-solves with the opponent selling whatever we just sold.

WHAT IS RELAXED (so the number is an upper bound, not a forecast)
  * integrality of tiles, animals and hands
  * movement: a worker-turn becomes a productive action at rate `--eff`
  * weeds, the 10-orders-per-turn cap, and any opponent reaction
  * within-day timing (a day is a pool of actions)

Usage:
    .venv/bin/python tools/lp_bound.py --eff 0.414
    .venv/bin/python tools/lp_bound.py --sweep
    .venv/bin/python tools/lp_bound.py --shops YARN_STORE,YARN_STORE --eff 1.0
"""

