def cumulative_drain(shops=None):
    """Units of each product the town has removed by the END of each day.

    Returns {product: [cum_day0, ..., cum_day29]}. With an explicit shop list
    every named instance opens on the real unlock schedule (days 3, 6, ...);
    with none, use the expected draw -- one uniform instance per unlock day.
    """
    cum = {p: [0.0] * DAYS for p in PRODUCTS}
    ticks = TURNS_PER_DAY / TOWN_SHOP_SELL_INTERVAL   # 6 consumption ticks/day

    per_day = {p: [0.0] * DAYS for p in PRODUCTS}
    for p in TOWN_CENTER_PRODUCTS:
        for d in range(DAYS):
            per_day[p][d] += 1.0                  # town centre, once a day

    if shops:
        for i, shop in enumerate(shops):
            u = UNLOCK_DAYS[i] if i < len(UNLOCK_DAYS) else UNLOCK_DAYS[-1]
            items = SHOPS[shop]
            mult = 2 if len(items) == 1 else 1
            for item in items:
                for d in range(u, DAYS):
                    per_day[item][d] += mult * ticks
    else:
        weights = econ.shop_weight_per_day()      # expected drain/day per unlock
        for i, u in enumerate(UNLOCK_DAYS):
            if i >= MAX_SHOP_INSTANCES:
                break
            for item, w in weights.items():
                for d in range(u, DAYS):
                    per_day[item][d] += w

    for p in PRODUCTS:
        run = 0.0
        for d in range(DAYS):
            run += per_day[p][d]
            cum[p][d] = run
    return cum


def revenue_bands(product, cum_drain_p, cum_opp_p=None, max_units=2000,
                  max_segments=40):
    """Day-aware price ladder: bands over CUMULATIVE units sold, priced per day.

    For any feasible schedule, the k-th unit we sell all season, sold on day d,
    faces a market inventory of at least

        I0 - (drain realised by day d) + (opponent's sales) + (k - 1)

    because drain is the only thing that lowers inventory and it has not all
    happened yet. Price falls with inventory, so pricing that unit at
    price(I0 - cum_drain[d] + k - 1) can only overstate what it fetches. Bands
    partition k; each band may be filled once over the season, at whatever day's
    price the LP picks. That keeps it a valid upper bound while making an early
    sale correctly cheap -- the previous flat ladder let a day-2 sale collect the
    whole season's scarcity premium.

    Returns (bands, prices) where bands[j] = width and prices[j][d] = $/unit.
    """
    I0 = MARKET_PARAMS[product]["I0"]
    cum_opp_p = cum_opp_p or [0.0] * DAYS
    # Band boundaries are chosen on the season-end baseline, where the price
    # spread over k is widest.
    end_base = I0 - cum_drain_p[-1] + cum_opp_p[-1]
    runs = []
    for k in range(max_units):
        p = econ.price(product, end_base + k)
        if p <= 1:
            break
        if runs and runs[-1][1] == p:
            runs[-1][0] += 1
        else:
            runs.append([1, p])
    if not runs:
        return [], []

    while len(runs) > max_segments:
        merged = []
        for i in range(0, len(runs), 2):
            if i + 1 < len(runs):
                merged.append([runs[i][0] + runs[i + 1][0], runs[i][1]])
            else:
                merged.append(runs[i])
        runs = merged

    bands, prices = [], []
    k = 0
    for width, _ in runs:
        bands.append(float(width))
        # Price the whole band at its first unit (over-credits within the band,
        # which keeps the bound valid).
        prices.append([float(econ.price(product, I0 - cum_drain_p[d] + cum_opp_p[d] + k))
                       for d in range(DAYS)])
        k += width
    return bands, prices


