"""Export the pointer network as a self-contained numpy module for the bundle.

Same two constraints as the BoardNet export: `submit.sh` forbids `open(`, so
weights are float16 base64 literals (52,289 params, ~105 KB), and a
pure-Python forward is far too slow, so numpy does the matmuls. numpy is
verified importable from an isolated agent.

Implements `nn.MultiheadAttention(batch_first=True)` in eval mode by hand:
`in_proj_weight` is the stacked (Wq;Wk;Wv), heads are a reshape, the padding
mask becomes -inf before the softmax, then `out_proj`. LayerNorm is the usual
affine standardisation. Verified against torch on real turns before use.

    PYTHONPATH=. uv run python tools/export_ptrnet.py --out /tmp/ptr.py
"""

import argparse
import base64
import os
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
MODEL = os.path.join(REPO, "rl/datasets/ptrnet.npz.model")

FORWARD = '''
# --- pointer network, numpy only --------------------------------------------
import base64 as _pb64
import numpy as _pnp

# Every bundle module execs into ONE dict, so loop variables leak. `_shape`
# collided with econ._shape (the price-curve helper) and turned price() into a
# list -- "'list' object is not callable". Keep every name _ptr-prefixed.
_PW = {}
for _ptr_k, _ptr_v in _PBLOB.items():
    _PW[_ptr_k] = _pnp.frombuffer(_pb64.b64decode(_ptr_v[0]), dtype=_pnp.float16
                                  ).astype(_pnp.float32).reshape(_ptr_v[1])
del _ptr_k, _ptr_v
_PHEADS = 4


def _pln(x, p):
    m = x.mean(-1, keepdims=True)
    v = x.var(-1, keepdims=True)
    return (x - m) / _pnp.sqrt(v + 1e-5) * _PW[p + ".weight"] + _PW[p + ".bias"]


def _pmha(q, kv, p, pad):
    """nn.MultiheadAttention(batch_first=True) in eval mode. q (Nq,d) kv (Nk,d)."""
    W = _PW[p + ".in_proj_weight"]
    b = _PW[p + ".in_proj_bias"]
    d = q.shape[-1]
    Q = q @ W[:d].T + b[:d]
    K = kv @ W[d:2 * d].T + b[d:2 * d]
    V = kv @ W[2 * d:].T + b[2 * d:]
    h = _PHEADS
    dh = d // h
    Q = Q.reshape(-1, h, dh).transpose(1, 0, 2)
    K = K.reshape(-1, h, dh).transpose(1, 0, 2)
    V = V.reshape(-1, h, dh).transpose(1, 0, 2)
    s = Q @ K.transpose(0, 2, 1) / _pnp.sqrt(dh)
    if pad is not None:
        s = _pnp.where(pad[None, None, :], -1e9, s)
    s = s - s.max(-1, keepdims=True)
    a = _pnp.exp(s)
    a = a / _pnp.maximum(a.sum(-1, keepdims=True), 1e-9)
    o = (a @ V).transpose(1, 0, 2).reshape(-1, d)
    return o @ _PW[p + ".out_proj.weight"].T + _PW[p + ".out_proj.bias"]


def _prelu(x):
    return _pnp.maximum(x, 0.0)


def _ptr_logits(U, T, D, tmask):
    """U (nu,6) T (nt,F) D (nu,nt) -> logits (nu,nt)."""
    h = _prelu(T @ _PW["te.0.weight"].T + _PW["te.0.bias"])
    h = h @ _PW["te.2.weight"].T + _PW["te.2.bias"]
    pad = ~tmask
    h = _pln(h + _pmha(h, h, "tsa", pad), "tln")
    u = _prelu(U @ _PW["ue.0.weight"].T + _PW["ue.0.bias"])
    u = u @ _PW["ue.2.weight"].T + _PW["ue.2.bias"]
    u = _pln(u + _pmha(u, h, "glimpse", pad), "gln")
    q = u @ _PW["wq.weight"].T + _PW["wq.bias"]
    k = h @ _PW["wk.weight"].T + _PW["wk.bias"]
    lg = q @ k.T / _pnp.sqrt(float(q.shape[-1]))
    lg = lg + float(_PW["dbias"]) * D
    return _pnp.where(tmask[None, :], lg, -1e9)
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=MODEL)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    import torch

    sd = torch.load(args.model, weights_only=True)
    blob, tot = {}, 0
    for k, v in sd.items():
        a = v.numpy().astype(np.float16)
        tot += a.size
        blob[k] = (base64.b64encode(a.tobytes()).decode("ascii"), list(a.shape))

    src = ['"""Pointer-network weights and numpy forward (generated by '
           'tools/export_ptrnet.py)."""\n', "_PBLOB = {"]
    for k, (b, shape) in blob.items():
        src.append("    %r: (%r, %r)," % (k, b, shape))
    src.append("}")
    src.append(FORWARD)
    open(args.out, "w").write("\n".join(src))
    print(f"  {tot:,} params -> {args.out} "
          f"({os.path.getsize(args.out)/1e3:.0f} KB)")

    # --- verify numpy == torch on random-but-shaped input ------------------
    z = np.load(os.path.join(REPO, "rl/datasets/ptrnet.npz"))
    from tools.ptrnet import build_net
    net = build_net(z["T"].shape[2], 64)
    net.load_state_dict(sd)
    net.eval()
    ns = {}
    exec(open(args.out).read(), ns)
    worst = 0.0
    for i in range(6):
        U, T, UM, TM, D = (z[k][i] for k in ("U", "T", "UM", "TM", "D"))
        with torch.no_grad():
            ref = net(torch.from_numpy(U[None]), torch.from_numpy(T[None]),
                      torch.from_numpy(UM[None]), torch.from_numpy(TM[None]),
                      torch.from_numpy(D[None]))[0].numpy()
        got = ns["_ptr_logits"](U, T, D, TM)
        m = UM[:, None] & TM[None, :]
        worst = max(worst, float(np.abs(ref[m] - got[m]).max()))
    print(f"  max |numpy - torch| on valid entries: {worst:.4f}")


if __name__ == "__main__":
    main()
