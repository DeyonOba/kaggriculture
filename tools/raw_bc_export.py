def export(args):
    import tools.raw_bc as rb
    wpath = os.path.join(DATA, "weights.json")
    if not os.path.exists(wpath):
        raise SystemExit(f"no weights at {wpath}; run `raw_bc.py fit` first")
    W = json.load(open(wpath))
    blob = base64.b85encode(zlib.compress(json.dumps(W).encode(), 9)).decode()

    src = inspect.getsource(rb.feats)
    code = TMPL.format(
        n_sess=args.n, rating=int(args.min_rating), acc=W["acc"],
        base=W["baseline"], thr=W.get("thr", 1.0),
        products=rb.PRODUCTS, crops=rb.CROPS_L,
        animals=rb.ANIMALS_L, shed=rb.SHED,
        actions=[list(a) for a in rb.UNIT_ACTIONS],
        market=[list(a) for a in rb.MARKET_ACTIONS], max_hire=rb.MAX_HIRE,
        blob=blob, feats_src=src)

    d = os.path.join(REPO, "arena", "agents", args.name)
    os.makedirs(d, exist_ok=True)
    p = os.path.join(d, "main.py")
    open(p, "w").write(code)
    compile(code, p, "exec")
    print(f"wrote {p} ({os.path.getsize(p)/1000:.0f} KB), "
          f"held-out accuracy {W['acc']:.4f} vs baseline {W['baseline']:.4f}")
    print("  now SMOKE TEST it -- a bundle that raises on import scores "
          "exactly $3,000 and looks valid")
