"""Export BoardNet into a self-contained bundle module: numpy forward + weights.

Two constraints shape this and both are measured, not assumed.

`tools/submit.sh` rejects any bundle containing the token `open(`, so the agent
cannot read a weights file -- the parameters have to be LITERALS in main.py.
326k float32 is 1.3 MB; stored float16 and base64'd it is ~0.9 MB, against a
100 MiB limit.

A pure-Python forward pass is out: the stem plus three residual blocks is ~28M
multiply-adds, which is ~30 s a call against a 1 s/turn budget. numpy does it
in 0.3 ms and was verified importable from an isolated agent (statuses
['DONE','DONE'] with the repo stripped from sys.path). So numpy is
load-bearing, not a convenience.

The encoder is NOT reimplemented. `policy.act_safe` stashes the raw
observation on `memory.last_raw_obs`, so the exact training encoder source is
inlined verbatim and fed the same dict it saw during training. A
reimplementation would be the obvious place for a silent train/serve skew.

    PYTHONPATH=. uv run python tools/export_boardnet.py \
        --model rl/datasets/boardnet_E.npz --arm E_full_83 --out /tmp/net.py
"""

import argparse
import base64
import os
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

FORWARD = '''
# --- BoardNet inference, numpy only -----------------------------------------
# Mirrors tools/boardnet.py in eval mode: stem(conv3-BN-ReLU), N residual
# blocks, then concat(avg-pool, max-pool) into a two-layer head. Dropout is
# identity at eval. BatchNorm folds to an affine map per channel.
import base64 as _b64
import numpy as _np

_W = {}
for _k, _b in _BLOB.items():
    _raw, _shape = _b
    _W[_k] = _np.frombuffer(_b64.b64decode(_raw), dtype=_np.float16
                            ).astype(_np.float32).reshape(_shape)
_MU = _W.pop("__mu")
_SD = _W.pop("__sd")
_BLOCKS = int(_NET_BLOCKS)


def _conv3(x, w):
    """(C,H,W) x (O,C,3,3) -> (O,H,W), zero-padded, stride 1."""
    c, h, wd = x.shape
    o = w.shape[0]
    xp = _np.zeros((c, h + 2, wd + 2), dtype=_np.float32)
    xp[:, 1:-1, 1:-1] = x
    out = _np.zeros((o, h, wd), dtype=_np.float32)
    for i in range(3):
        for j in range(3):
            out += (w[:, :, i, j] @ xp[:, i:i + h, j:j + wd].reshape(c, -1)
                    ).reshape(o, h, wd)
    return out


def _bn(x, p):
    g, b, m, v = (_W[p + ".weight"], _W[p + ".bias"],
                  _W[p + ".running_mean"], _W[p + ".running_var"])
    s = g / _np.sqrt(v + 1e-5)
    return x * s[:, None, None] + (b - m * s)[:, None, None]


def _boardnet_forward(x):
    """(C,10,10) -> flow vector in ORIGINAL units."""
    h = _np.maximum(_bn(_conv3(x, _W["stem.0.weight"]), "stem.1"), 0.0)
    for i in range(_BLOCKS):
        p = "blocks.%d." % i
        t = _np.maximum(_bn(_conv3(h, _W[p + "c1.weight"]), p + "b1"), 0.0)
        t = _bn(_conv3(t, _W[p + "c2.weight"]), p + "b2")
        h = _np.maximum(h + t, 0.0)
    g = _np.concatenate([h.mean(axis=(1, 2)), h.max(axis=(1, 2))])
    z = _np.maximum(g @ _W["head.0.weight"].T + _W["head.0.bias"], 0.0)
    z = z @ _W["head.3.weight"].T + _W["head.3.bias"]
    return z * _SD + _MU
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--arm", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    from tools.board_tensor import arm_channels

    d = np.load(args.model)
    meta = d["__meta"]
    blocks = int(meta[3])
    keep = [k for k in d.files
            if not k.startswith("aux.") and not k.startswith("shed.")
            and k != "__meta"]
    blob = {}
    total = 0
    for k in keep:
        a = np.asarray(d[k], dtype=np.float16)
        total += a.size
        blob[k] = (base64.b64encode(a.tobytes()).decode("ascii"),
                   list(a.shape))

    cols = arm_channels(args.arm)
    src = []
    src.append('"""BoardNet weights and a numpy forward pass (generated).\n\n'
               'Generated by tools/export_boardnet.py from %s, arm %s.\n'
               'Weights are float16 literals because submit.sh forbids open().\n'
               '"""\n' % (os.path.basename(args.model), args.arm))
    src.append("_NET_BLOCKS = %d" % blocks)
    src.append("_NET_ARM_COLS = %r" % (cols,))
    src.append("_NET_HORIZON = 10")
    src.append("_NET_PRODUCTS = ['WHEAT','CARROT','TOMATO','STRAWBERRY',"
               "'MELON','EGG','MILK','WOOL','FERTILIZER']")
    src.append("_BLOB = {")
    for k, (b, shape) in blob.items():
        src.append("    %r: (%r, %r)," % (k, b, shape))
    src.append("}")
    src.append(FORWARD)

    # the encoder, verbatim from the training source -- no reimplementation
    enc = open(os.path.join(REPO, "tools", "board_tensor.py")).read()
    enc = enc.replace("import numpy as np", "import numpy as np  # noqa", 1)
    enc = enc.replace("from kagent.constants import MARKET_PARAMS",
                      "pass  # MARKET_PARAMS is already a bundle global")
    # Every bundle module execs into ONE shared namespace, so a top-level name
    # that also exists in the agent would silently shadow it. Measured against
    # r-mrg100: FIRST_YIELD and counts collide. Namespace them; `counts` is the
    # ridge baseline and has no role at inference, so it is dropped outright.
    enc = enc.replace("FIRST_YIELD", "_BT_FIRST_YIELD")
    i = enc.find("def counts(obs, seat=0):")
    j = enc.find("\nN_COUNT = ", i)
    if i > 0 and j > i:
        enc = enc[:i] + enc[enc.find("\n", j + 1) + 1:]
    src.append("\n# --- encoder, inlined verbatim from tools/board_tensor.py --\n")
    src.append(enc)
    src.append('''

def _net_opp_flow(obs):
    """-> [{}] + H dicts of product -> net units the opponent adds that day."""
    t = board_pair_full(obs, obs.get("player", 0))
    x = _np.ascontiguousarray(t[_NET_ARM_COLS], dtype=_np.float32)
    z = _boardnet_forward(x).reshape(_NET_HORIZON, len(_NET_PRODUCTS))
    return [{}] + [{p: float(z[j, i]) for i, p in enumerate(_NET_PRODUCTS)}
                   for j in range(_NET_HORIZON)]
''')
    open(args.out, "w").write("\n".join(src))
    n = os.path.getsize(args.out)
    print(f"{args.arm}: {total:,} weights, {len(cols)} input channels, "
          f"{blocks} blocks -> {args.out} ({n/1e6:.2f} MB)")


if __name__ == "__main__":
    main()
